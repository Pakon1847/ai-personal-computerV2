"""ประโยคคำสั่งเสียงที่ระบบทำได้ (การ์ด 0045) · ที่เดียว ใช้สองที่:

1. คำใบ้ (hotwords) ของ Zipformer ทางคีย์ลัด (aipc.voice.zipformer.HOTWORDS ต่อท้ายด้วยรายการนี้)
2. ได้ยินใกล้เคียง = ถามก่อน "หมายถึง … ใช่ไหม" (near_command · BRIEF 5.6 ข้อ 2: fuzzy กับผลยืนยันเท่านั้น)

ทุกประโยคต้องเป็นคำสั่งที่ตัวแปลรู้จักอยู่แล้ว (เทสต์ตรวจ) · เขียนจากความสามารถของระบบ ไม่ได้มาจากชุดทดสอบ
"""

from __future__ import annotations

import re
from difflib import SequenceMatcher

COMMANDS = (
    # หน้าในระบบ · แอป
    "เปิดหน้าตั้งค่า", "เปิดหน้าปฏิทิน", "เปิดหน้าไฟล์", "เปิดหน้าสกิล", "เปิดหน้าสุขภาพเครื่อง",
    "เปิดเบราว์เซอร์", "เปิดเทอร์มินัล",
    # เสียงของเครื่อง
    "เพิ่มเสียง", "ลดเสียง", "ปิดเสียง", "เปิดเสียง",
    # เว็บที่เพิ่มหลังการ์ด 0026
    "เปิดเน็ตฟลิกซ์", "เปิดสปอติฟาย", "เปิดข่าว", "เปิดดิสนีย์พลัส", "เปิดกูเกิลด็อก",
    # คุมเพลง/วิดีโอ/หน้าเว็บ (การ์ด 0042)
    "เพลงก่อนหน้า", "เล่นวิดีโอ", "เต็มจอ", "ออกจากเต็มจอ", "ข้ามโฆษณา", "รีเซ็ตหน้า",
    "เข้าคลิปแรก", "ดูคลิปที่สอง",
    # ค่าตั้งของแอป (การ์ด 0042 รอบ 3)
    "เปิดโหมดมืด", "เปิดโหมดสว่าง", "ตัวหนังสือใหญ่ขึ้น", "ตัวหนังสือเล็กลง",
    "เปลี่ยนเป็นภาษาอังกฤษ", "เปลี่ยนเป็นภาษาไทย", "แชทใหม่",
    # คำถามที่โค้ดตอบ (การ์ด 0029)
    "ตอนนี้กี่โมง", "วันนี้มีนัดอะไร", "พรุ่งนี้มีนัดอะไร", "ทำไมเครื่องช้า", "เครื่องร้อนไหม",
)  # fmt: skip
# ต้นประโยค (ไม่ใช่คำสั่งเต็ม) · ใช้เป็นคำใบ้อย่างเดียว ไม่ใช้เทียบใกล้เคียง
STEMS = ("เตือน", "อย่าลืม", "ปลุก", "ค้นในสปอติฟาย", "ค้นในเน็ตฟลิกซ์")

NEAR_MIN = 0.75  # ความคล้ายขั้นต่ำ (0–1) · ตั้งจากชุดพัฒนา voice_cmd_dev
_MARKS = re.compile("[็-๎ั]")  # ไม้ไต่คู้ วรรณยุกต์ การันต์ นิคหิต ไม้หันอากาศ
_PAIRS = str.maketrans({"ี": "ิ", "ื": "ึ", "ู": "ุ", "ใ": "ไ", "ฅ": "ค", "ฃ": "ข"})


def _sound(text: str) -> str:
    """รูปที่ใช้เทียบ: ตัดช่องว่าง วรรณยุกต์ เครื่องหมาย · รวมสระสั้น-ยาว (ตัวถอดมักพลาดตรงนี้)."""
    return _MARKS.sub("", re.sub(r"\s+", "", text)).translate(_PAIRS)


_CATALOG = [(c, _sound(c)) for c in COMMANDS]


def near_command(text: str) -> str:
    """ประโยคคำสั่งที่ใกล้ที่สุด ถ้าใกล้พอ (≥ NEAR_MIN · ยาวใกล้เคียงกัน) · ไม่ใกล้ = ""."""
    s = _sound(text)
    if len(s) < 4:
        return ""
    best, score = "", 0.0
    for phrase, p in _CATALOG:
        if not 0.7 <= len(s) / len(p) <= 1.4:
            continue
        r = SequenceMatcher(None, s, p).ratio()
        if r > score:
            best, score = phrase, r
    return best if score >= NEAR_MIN else ""
