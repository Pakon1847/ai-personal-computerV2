def texts(m: Manifest) -> list[tuple[str, str]]:
    """ข้อความทุกช่องที่ผู้ใช้เห็น หรือ AI ได้อ่าน (รายการเครื่องมือ · prompt · ขั้นตอน)."""
    out = [("ชื่อ", m.name), ("คำอธิบาย", m.description), ("คำสั่งให้ AI", m.prompt)]
    out += [("คำสำคัญ", k) for k in m.keywords] + [("ตัวอย่าง", e) for e in m.examples]
    for s in m.steps:
        if s.kind == "say":
            out.append(("ขั้น บอก", s.text))
        elif s.kind == "llm":
            out.append(("ขั้น ถาม AI", s.text))
    out += [("คำพูดสั่งเว็บ", p) for c in m.commands for p in c.phrases]
    return [(f, t) for f, t in out if t]


def check(m: Manifest, skill_md: str = "") -> list[str]:
    """เหตุผลที่ไม่ผ่าน (ภาษาคน) · รายการว่าง = ผ่าน."""
    errors = []
    if INVISIBLE.search(skill_md.removeprefix("﻿")):
        errors.append("ไฟล์มีอักขระที่มองไม่เห็น (ใช้ซ่อนคำสั่งได้) · สกิลปกติไม่ต้องใช้")
    found: dict[str, str] = {}
    for field, text in texts(m):
        for name in FIELDS[field]:
            if name not in found and RULES[name][0].search(text):
                found[name] = field
    errors += [f"{RULES[name][1]} · ช่อง{field}" for name, field in found.items()]
    return errors
